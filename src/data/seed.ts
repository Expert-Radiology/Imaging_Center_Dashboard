/**
 * The bundled fallback snapshot — the hand-maintained board as of Sep 2 2026,
 * transcribed from the design reference.
 *
 * It exists so the dashboard is functional before the ClickUp Function is wired,
 * and so a failed refresh has something to render. `source: 'seed'` drives the
 * "showing the bundled snapshot" state in the freshness strip — the UI never
 * passes seed data off as live.
 *
 * Values that ClickUp has no field for (HL7 VPN, HL7 testing, facility/station
 * split, estimated deployment) are listed per row in `unsourced` and are the
 * reason the four-missing-fields callout renders.
 */

/** Compact glyph codes: D done · P in progress · N not done · - not in scope. */
const GLYPH: Record<string, Glyph> = {
  D: 'done',
  P: 'progress',
  N: 'notdone',
  '-': 'na',
};

function milestones(code: string): Milestones {
  const g = [...code].map((c) => GLYPH[c]);
  return {
    vpnForm: g[0],
    ping: g[1],
    testStudy: g[2],
    headerTemplate: g[3],
    ramsoftStation: g[4],
  };
}

function lineItems(code: string): MatrixLineItems {
  const g = [...code].map((c) => GLYPH[c]);
  return {
    dicomVpn: g[0],
    hl7Vpn: g[1],
    dicomStudy: g[2],
    hl7Test: g[3],
    facility: g[4],
    station: g[5],
    headerDotx: g[6],
  };
}

