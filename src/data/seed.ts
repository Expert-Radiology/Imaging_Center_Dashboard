function toConnection(row: Row): Connection {
  return {
    id: row.id,
    // Placeholder task ids — the live payload carries real ClickUp ids and the
    // center name links to app.clickup.com/t/{id}. Seed rows do not link.
    centerId: '',
    centerName: row.name,
    qualifier: row.qualifier ?? null,
    connectionType: row.type,
    pacsVendor: row.pacs ?? null,
    owner: row.owner,
    state: row.st ?? null,
    locationCount: row.locations ?? null,
    startDate: row.startDate ?? null,
    daysInPipeline: row.days ?? null,
    percentComplete: row.pct,
    status: row.status,
    onHold: row.onHold ?? false,
    newThisWeek: row.newThisWeek ?? false,
    urgent: row.urgent ?? false,
    blockerGroup: row.group ?? null,
    blockerText: row.blocker,
    waitingOn: row.waitingOn,
    nextAction: row.next,
    estimatedDeployment: {
      label: row.est,
      proposed: row.proposed ?? true,
    },
    ramsoftTicketId: row.ticket ?? null,
    milestones: milestones(row.ms),
    lineItems: lineItems(row.li),
    finalFlag: row.onHold ? 'onhold' : 'notdone',
    lastActivityAt: row.lastActivityAt ?? null,
    // Every row: none of these four have a ClickUp field yet.
    unsourced: [
      'hl7VpnStatus',
      'hl7TestingStatus',
      'facilityStationSplit',
      'estimatedDeploymentDate',
    ],
  };
}

